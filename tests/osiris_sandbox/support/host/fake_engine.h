/*
 * A recording fake of the engine side of the OSIRIS API, so the sandbox bridge
 * (Descent3/osiris_sandbox.cpp) can be tested without the game. Every call is
 * appended to g_calls as "name(arg, arg, ...)". Most fakes are generated by
 * gen_fakes.py; fake_engine.cpp has the ones whose behaviour the tests use.
 */

#ifndef FAKE_ENGINE_H
#define FAKE_ENGINE_H

#include <cstdint>
#include <map>
#include <string>
#include <vector>

#include "osiris_dll.h"
#include "vecmat_external.h"

struct CFILE;

extern std::vector<std::string> g_calls;
// Files the fake cfopen can open, by name.
extern std::map<std::string, std::string> g_files;

void rec_begin(const char *name);
void rec_i(long long v);
void rec_f(double v);
void rec_str(const char *s);
void rec_ptr(const void *p);
void rec_vec(const vector *v);
void rec_end();

// The ID the fake engine returns for a named object, room, path and so on.
int fake_id(const char *kind, const char *name);

// In-memory files for save and restore.
CFILE *fake_new_file(const std::vector<uint8_t> &data);
const std::vector<uint8_t> &fake_file_data(CFILE *f);
void fake_free_file(CFILE *f);

template <class T> T fake_ret() { return T{}; }

// Clears the recorded calls and the fake engine's counters, for test isolation.
void fake_reset();

// Fills the function table in the engine's order (generated).
void fill_module_init(tOSIRISModuleInit *mi);

#endif
