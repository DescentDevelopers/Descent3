"""Generates the recording fakes of the engine functions for osiris_sandbox_tests.

Usage: gen_fakes.py <source root> <output .cpp>

The output defines:
  - a fake for every osipf_* function in Descent3/osiris_predefs.h, except the
    ones fake_engine.cpp writes by hand. Each records "name(args)" and returns
    a zero value.
  - fill_module_init(), which fills tOSIRISModuleInit::fp in the order of the
    engine's Osiris_CreateModuleInitStruct. The test takes the order from the
    engine source, not from the bridge, so the bridge's own table check is
    tested against an independent source.
"""

import re
import sys

# Fakes with behaviour the tests depend on; written in fake_engine.cpp.
HAND_WRITTEN = {
    'osipf_CallObjectEvent', 'osipf_CFopen', 'osipf_CFclose', 'osipf_CFeof', 'osipf_CFReadString',
    'osipf_CFReadInt', 'osipf_CFReadFloat', 'osipf_CFReadByte', 'osipf_CFReadBytes', 'osipf_CFWriteInt',
    'osipf_CFWriteFloat', 'osipf_CFWriteByte', 'osipf_CFWriteBytes', 'osipf_ObjectValue', 'osipf_FindDoorName',
    'osipf_FindObjectName', 'osipf_FindRoomName', 'osipf_FindTriggerName', 'osipf_FindSoundName',
    'osipf_FindTextureName', 'osipf_FindPathName', 'osipf_FindMatcenName', 'osipf_FindLevelGoalName',
    'osipf_GetLanguageSetting', 'osipf_GameTime', 'osipf_FrameTime', 'osipf_AIGoalAdd',
    'osipf_PlayerAddHudMessage', 'osipf_RayCast', 'osipf_AIGetRoomPathPoint',
}

# Engine functions in the table that are not osipf_* functions.
OTHER_API = {
    'msafe_CallFunction', 'msafe_GetValue', 'msafe_DoPowerup', 'Osiris_AllocateMemory', 'Osiris_FreeMemory',
    'Osiris_CancelTimer', 'Osiris_CreateTimer', 'Osiris_TimerExists', 'Cinematic_Start', 'Cinematic_Stop',
    'Osiris_CancelTimerID', 'Cinematic_StartCannedScript',
}


def strip_comments(text):
    text = re.sub(r'//[^\n]*', '', text)
    return re.sub(r'/\*.*?\*/', '', text, flags=re.S)


def recorder(type_name, name):
    t = ' '.join(type_name.split())
    if t in ('char *', 'const char *', 'char*', 'const char*'):
        return f'rec_str({name})'
    if t in ('vector *', 'vector*'):
        return f'rec_vec({name})'
    if '*' in t or '&' in t:
        return f'rec_ptr({name})'
    if t in ('float', 'double'):
        return f'rec_f({name})'
    if t == 'bool':
        return f'rec_i({name} ? 1 : 0)'
    return f'rec_i(static_cast<long long>({name}))'


def parse_params(args):
    args = ' '.join(args.split())
    params = []
    if not args or args == 'void':
        return params
    for i, a in enumerate(args.split(',')):
        a = a.split('=')[0].strip()  # drop default arguments
        if a == '...':
            params.append(('...', None))
            continue
        m = re.match(r'(.*?)(\w+)$', a)
        if m and m.group(1).strip():
            params.append((m.group(1).strip(), m.group(2)))
        else:
            params.append((a, f'a{i}'))
    return params


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    predefs = strip_comments(open(f'{root}/Descent3/osiris_predefs.h').read())
    protos = re.findall(r'^\s*((?:const\s+)?[A-Za-z_]\w*\s*\**)\s*(osipf_\w+)\s*\(([^;{]*?)\)\s*;', predefs,
                        re.M | re.S)
    if len(protos) < 100:
        sys.exit(f'gen_fakes.py: found only {len(protos)} osipf_ prototypes; the header format changed')

    out = []
    out.append('// Generated by tests/osiris_sandbox/support/host/gen_fakes.py. Do not edit.\n')
    out.append('#include "fake_engine.h"\n#include "gamecinematics.h"\n#include "multisafe.h"\n'
               '#include "osiris_dll.h"\n#include "osiris_predefs.h"\n\n')
    out.append('extern void Osiris_CancelTimerID(int id);\n'
               'extern void Cinematic_StartCannedScript(tCannedCinematicInfo *info);\n\n')
    for ret, name, args in protos:
        if name in HAND_WRITTEN:
            continue
        params = parse_params(args)
        decl = ', '.join(p[0] if p[0] == '...' else f'{p[0]} {p[1]}' for p in params)
        ret = ' '.join(ret.split())
        body = [f'  rec_begin("{name}");']
        body += [f'  {recorder(t, n)};' for t, n in params if t != '...']
        body.append('  rec_end();')
        if ret != 'void':
            body.append(f'  return fake_ret<{ret}>();')
        out.append(f'{ret} {name}({decl}) {{\n' + '\n'.join(body) + '\n}\n\n')

    loader = strip_comments(open(f'{root}/Descent3/OsirisLoadandBind.cpp').read())
    start = loader.index('void Osiris_CreateModuleInitStruct(tOSIRISModuleInit *mi) {')
    body = loader[start:loader.index('\n}\n', start)]
    names = re.findall(r'mi->fp\[i\+\+\]\s*=\s*\(int \*\)(\w+);', body)
    known = {p[1] for p in protos} | OTHER_API
    out.append('static void fake_unused_api() {}\n\n')
    out.append('void fill_module_init(tOSIRISModuleInit *mi) {\n  int i = 0;\n')
    for n in names:
        target = n if n in known else 'fake_unused_api'
        out.append(f'  mi->fp[i++] = reinterpret_cast<int32_t *>({target}); // {n}\n')
    out.append('}\n')
    with open(out_path, 'w') as f:
        f.write(''.join(out))


if __name__ == '__main__':
    main()
